"""Copy the model-mark SVG library into the app and regenerate its lookup table.

Run from the repository root after editing model-marks/catalog.csv:

    python3 tools/sync-model-marks.py
"""

import argparse
import csv
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "model-marks" / "catalog.csv"
ASSETS = ROOT / "app" / "src" / "main" / "assets" / "models"
TABLE = ROOT / "app" / "src" / "main" / "java" / "app" / "kai" / "photomark" / "ModelMarks.kt"

FAMILIES = {
    "Nikon": "NIKON", "Canon": "CANON", "Sony": "SONY", "Fujifilm": "FUJIFILM",
    "Panasonic LUMIX": "LUMIX", "OM SYSTEM": "OM_SYSTEM", "Pentax": "PENTAX",
}
# Names that EXIF writes differently from the catalog title.
ALIASES = {"PEN E-P7": ["E-P7"]}
# Series marks that do not identify a single body.
SKIP = {"PEN"}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check without writing files")
    check = parser.parse_args().check
    with CATALOG.open(encoding="utf-8") as catalog:
        rows = [row for row in csv.DictReader(catalog) if row["SVG"] and row["型号"] not in SKIP]
    if check:
        actual = {p.relative_to(ASSETS).as_posix() for p in ASSETS.rglob("*.svg")}
        if actual != {row["SVG"] for row in rows}:
            raise SystemExit("Android model asset list differs from catalog.csv")
    if not check and ASSETS.exists():
        shutil.rmtree(ASSETS)
    lines = []
    models = []
    for row in rows:
        source = ROOT / "model-marks" / row["SVG"]
        target = ASSETS / row["SVG"]
        if check:
            if source.read_bytes() != target.read_bytes():
                raise SystemExit(f"Stale camera mark: {target}")
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source, target)
        models.append([row["SVG"], row["型号"], *ALIASES.get(row["型号"], [])])
        aliases = "".join(f', "{alias}"' for alias in ALIASES.get(row["型号"], []))
        lines.append(f'    ModelMark(BrandMark.{FAMILIES[row["品牌"]]}, "{row["型号"]}", "models/{row["SVG"]}"{aliases}),')
    kotlin = (
        "package app.kai.photomark\n\n"
        "// Generated by tools/sync-model-marks.py from model-marks/catalog.csv. Do not edit by hand.\n"
        "internal val modelMarks = listOf(\n" + "\n".join(lines) + "\n)\n"
    )
    manifest = json.dumps(models, ensure_ascii=False, indent=2) + "\n"
    for file, content in [(TABLE, kotlin), (ROOT / "cli" / "models.json", manifest)]:
        if check:
            if file.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Stale catalog: {file}")
        else:
            file.write_text(content, encoding="utf-8")
    print(f"{len(rows)} model marks")


if __name__ == "__main__":
    main()
